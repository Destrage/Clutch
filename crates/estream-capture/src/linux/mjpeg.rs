//! Motion-JPEG frames from UVC cameras often leave out their Huffman tables and rely on the
//! standard ones (JPEG Annex K.3, as in the AVI1 format). Decoders want them in the file.

/// `jpeg` with the standard tables inserted after its start marker if it has none before
/// its scan (written into `out`), or `jpeg` itself.
pub fn with_huffman_tables<'a>(jpeg: &'a [u8], out: &'a mut Vec<u8>) -> &'a [u8] {
    if jpeg.len() < 4 || jpeg[..2] != [0xFF, 0xD8] || has_tables(jpeg) {
        return jpeg;
    }
    out.clear();
    out.extend_from_slice(&jpeg[..2]);
    out.extend_from_slice(&STANDARD_DHT);
    out.extend_from_slice(&jpeg[2..]);
    out
}

/// Whether a DHT segment comes before the first scan (walking the marker segments).
fn has_tables(jpeg: &[u8]) -> bool {
    let mut i = 2;
    while i + 4 <= jpeg.len() && jpeg[i] == 0xFF {
        match jpeg[i + 1] {
            0xC4 => return true,
            0xDA => return false,
            // Fill bytes before a marker.
            0xFF => i += 1,
            _ => i += 2 + u16::from_be_bytes([jpeg[i + 2], jpeg[i + 3]]) as usize,
        }
    }
    false
}

