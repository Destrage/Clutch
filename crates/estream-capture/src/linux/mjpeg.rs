#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_lengths_match_their_counts() {
        assert_eq!(
            u16::from_be_bytes([STANDARD_DHT[2], STANDARD_DHT[3]]) as usize,
            420 - 2
        );
        let mut i = 4;
        let mut tables = 0;
        while i < STANDARD_DHT.len() {
            let values: usize = STANDARD_DHT[i + 1..i + 17]
                .iter()
                .map(|&n| n as usize)
                .sum();
            i += 17 + values;
            tables += 1;
        }
        assert_eq!((i, tables), (STANDARD_DHT.len(), 4));
    }

    #[test]
    fn tables_go_in_only_when_missing() {
        // SOI, a DQT segment of length 4, then SOS.
        let bare = [0xFF, 0xD8, 0xFF, 0xDB, 0x00, 0x04, 0x00, 0x00, 0xFF, 0xDA];
        let mut out = Vec::new();
        let fixed = with_huffman_tables(&bare, &mut out).to_vec();
        assert_eq!(fixed.len(), bare.len() + STANDARD_DHT.len());
        assert_eq!(&fixed[2..4], &[0xFF, 0xC4]);
        assert!(has_tables(&fixed));
        let mut again = Vec::new();
        assert_eq!(
            with_huffman_tables(&fixed, &mut again),
            &fixed[..],
            "left alone"
        );
    }
}
